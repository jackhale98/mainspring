// Builds the TJP parser from src/lib/tjp/grammar/tjp.grammar (phase-1 spec 4, 5, task T5):
// parser.generated.ts and parser.terms.generated.ts, both committed.
//
//   npm run build:grammar [-- --check]
//
// --check regenerates in memory and exits 1 if either committed file differs, so CI catches a
// grammar change that was not rebuilt. Generator warnings (conflicts, unused rules) fail the build.
//
// The pure helpers (generate, compareFile) are exported for tests/scripts/build-grammar.test.ts.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const GRAMMAR = 'src/lib/tjp/grammar/tjp.grammar';
export const PARSER_OUT = 'src/lib/tjp/grammar/parser.generated.ts';
export const TERMS_OUT = 'src/lib/tjp/grammar/parser.terms.generated.ts';

/** @param {string} what */
const header = (what) =>
	[
		'// SPDX-License-Identifier: GPL-2.0-only',
		`// GENERATED by scripts/build-grammar.mjs from tjp.grammar (${what}); do not edit.`,
		"// tjp.grammar follows TaskJuggler's TjpSyntaxRules.rb at 3b36c79, so this file is",
		'// GPL-2.0-only too (ADR-0001 addendum).',
		'// Run `npm run build:grammar` after changing the grammar; CI runs it with --check.',
		'// May exceed 400 lines: it is generated parse-table data.',
		'',
	].join('\n');

/**
 * Formats a module with the repository's Prettier config, so format:check accepts it.
 * @param {string} source
 * @param {string} out
 */
async function format(source, out) {
	const prettier = await import('prettier');
	const filepath = path.join(REPO, out);
	const options = (await prettier.resolveConfig(filepath)) ?? {};
	return prettier.format(source, { ...options, filepath });
}

/**
 * Generates both modules from the grammar text. Throws on any generator warning.
 * @param {string} grammar
 * @returns {Promise<{ parser: string, terms: string }>}
 */
export async function generate(grammar) {
	const { buildParserFile } = await import('@lezer/generator');
	/** @type {string[]} */
	const warnings = [];
	const built = buildParserFile(grammar, {
		fileName: path.basename(GRAMMAR),
		moduleStyle: 'es',
		typeScript: true,
		warn: (message) => warnings.push(message),
	});
	// ScanError (an unterminated construct, which runs to the end of the file) and UnknownWord (an
	// unknown attribute name starting a line) are deliberately accepted nowhere, so the parser
	// turns them into error nodes.
	const unexpected = warnings.filter((w) => !/^Unused rule '(ScanError|UnknownWord)'/.test(w));
	if (unexpected.length > 0) {
		throw new Error(`lezer-generator warnings:\n${unexpected.join('\n')}`);
	}
	return {
		parser: await format(header('parse tables') + built.parser, PARSER_OUT),
		terms: await format(header('term ids') + built.terms, TERMS_OUT),
	};
}

/**
 * How a committed file compares with the fresh one, for --check.
 * @param {string} name
 * @param {string | null} committed
 * @param {string} fresh
 * @returns {string | null} null when they are equal, else what differs
 */
export function compareFile(name, committed, fresh) {
	if (committed === fresh) return null;
	if (committed === null) return `${name} is missing`;
	const a = committed.split('\n');
	const b = fresh.split('\n');
	let i = 0;
	while (i < a.length && a[i] === b[i]) i++;
	const clip = (/** @type {string | undefined} */ s) =>
		s === undefined ? '<end of file>' : s.length > 120 ? `${s.slice(0, 120)}…` : s;
	return (
		`${name} is stale; first difference at line ${i + 1}:\n` +
		`  committed: ${clip(a[i])}\n` +
		`  generated: ${clip(b[i])}`
	);
}

async function main() {
	const { values } = parseArgs({ options: { check: { type: 'boolean', default: false } } });
	const grammar = fs.readFileSync(path.join(REPO, GRAMMAR), 'utf8');
	const fresh = await generate(grammar);
	const outputs = /** @type {const} */ ([
		[PARSER_OUT, fresh.parser],
		[TERMS_OUT, fresh.terms],
	]);
	if (values.check) {
		const problems = outputs
			.map(([out, text]) => {
				const file = path.join(REPO, out);
				return compareFile(out, fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null, text);
			})
			.filter((p) => p !== null);
		if (problems.length > 0) {
			console.error(
				`build-grammar --check:\n${problems.join('\n')}\nRun npm run build:grammar and commit.`,
			);
			return 1;
		}
		console.log('build-grammar --check: the generated parser is up to date');
		return 0;
	}
	for (const [out, text] of outputs) {
		fs.writeFileSync(path.join(REPO, out), text);
		console.log(`${out}: ${Buffer.byteLength(text)} bytes`);
	}
	return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	main().then(
		(code) => process.exit(code),
		(error) => {
			console.error(error instanceof Error ? error.message : error);
			process.exit(1);
		},
	);
}
