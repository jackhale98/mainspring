// Generates the Gantt scale plans engine/golden/plans/gantt/gantt-200/plan.tjp and
// engine/golden/plans/gantt/gantt-500/plan.tjp (phase-2 spec, section 14, T3).
// Deterministic: a seeded mulberry32 PRNG per size, no Math.random, no clock.
// Each plan has exactly N `task` declarations (containers included), 10 or 20 resources, and
// dependencies within packages, between packages of a phase, and from each phase's milestone to
// the next phase. Run from anywhere: node engine/golden/generators/gantt-plans.mjs
// Check mode: node engine/golden/generators/gantt-plans.mjs --check (exit 1 if a committed file differs).
// SPDX-License-Identifier: GPL-2.0-or-later
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const LEAVES_PER_PACKAGE = 8;
const TASKS_PER_PHASE = 50; // phase container + milestone + packages with their leaves

/** Sizes: task count, resource count and the 32-bit seed. */
const SIZES = [
  { n: 200, resources: 10, seed: 0x6a77a200 },
  { n: 500, resources: 20, seed: 0x6a77a500 },
];

function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Plan data first (phases, packages, leaves), then text, so every reference can be checked. */
function buildTree(n, rnd) {
  const pick = (k) => Math.floor(rnd() * k);
  const phases = [];
  let remaining = n;
  let seq = 0;
  const newLeaf = () => ({ seq: ++seq });
  while (remaining > 0) {
    if (remaining < 4) {
      // Too few tasks for a phase: the rest become leaves of the last package.
      const last = phases[phases.length - 1];
      const pkg = last.pkgs[last.pkgs.length - 1];
      for (let i = 0; i < remaining; i++) pkg.leaves.push(newLeaf());
      remaining = 0;
      break;
    }
    const total = Math.min(remaining, TASKS_PER_PHASE);
    remaining -= total;
    const phase = { index: phases.length, pkgs: [] };
    let budget = total - 2; // the phase container and its milestone
    while (budget >= 2) {
      const leaves = Math.min(LEAVES_PER_PACKAGE, budget - 1);
      const pkg = { index: phase.pkgs.length, leaves: [] };
      for (let i = 0; i < leaves; i++) pkg.leaves.push(newLeaf());
      phase.pkgs.push(pkg);
      budget -= 1 + leaves;
    }
    if (budget === 1) phase.pkgs[phase.pkgs.length - 1].leaves.push(newLeaf());
    phases.push(phase);
  }

  // Attributes, drawn in a fixed order so the output is reproducible.
  for (const phase of phases) {
    for (const pkg of phase.pkgs) {
      pkg.leaves.forEach((leaf, j) => {
        const s = leaf.seq;
        const kind = s % 10;
        if (kind <= 6) leaf.size = `effort ${1 + (s * 7) % 8}d`;
        else if (kind <= 8) leaf.size = `length ${2 + (s % 4)}d`;
        else leaf.size = `duration ${1 + (s % 3)}d`;
        if (phase.index === 0) leaf.complete = 100;
        else if (phase.index === 1 && s % 2 === 0) leaf.complete = 40;
        // Only effort leaves are allocated: TaskJuggler warns about allocations it cannot fill.
        const withAllocation = kind <= 6;
        if (withAllocation) {
          leaf.alloc = [pick(n === 200 ? 10 : 20)];
          if (s % 5 === 0) leaf.alloc.push((leaf.alloc[0] + 1 + pick(3)) % (n === 200 ? 10 : 20));
        }
        const r = rnd();
        if (j > 0) {
          const prev = pkg.leaves[j - 1].seq;
          if (r < 0.2) leaf.dep = `!t${prev} { gaplength ${1 + pick(3)}d }`;
          else if (r < 0.3) leaf.dep = `!t${prev} { gapduration ${1 + pick(2)}d }`;
          else if (r < 0.4) leaf.dep = `!t${prev} { onstart }`;
          else leaf.dep = `!t${prev}`;
        } else if (pkg.index % 2 === 1) {
          // odd packages wait for the previous package of the phase (chains of two)
          const prev = phase.pkgs[pkg.index - 1].leaves;
          const lastSeq = prev[prev.length - 1].seq;
          leaf.dep = `p${phase.index}.p${phase.index}k${pkg.index - 1}.t${lastSeq}`;
        } else if (phase.index > 0) {
          // other packages start when the previous phase's milestone is reached
          leaf.dep = `p${phase.index - 1}.ms${phase.index - 1}`;
        }
      });
    }
  }
  return phases;
}

/** The plan text for one size. Every `depends` target is checked to exist before it is written. */
export function ganttPlan(n, resources, seed) {
  const rnd = mulberry32(seed);
  const phases = buildTree(n, rnd);
  const out = [];
  const w = (s = '') => out.push(s);
  const resCount = resources;

  w(`# Feature: gantt-${n} - generated Gantt scale plan: ${n} tasks, ${resCount} resources, phase/package/leaf nesting, dependencies with gaps and onstart, allocations, milestones and progress`);
  w(`# Generated by engine/golden/generators/gantt-plans.mjs (seed 0x${seed.toString(16)}, 32-bit). Do not hand-edit; regenerate with the script.`);
  w('# SPDX-License-Identifier: GPL-2.0-or-later');
  w(`project gantt${n} "Gantt ${n}" 2026-01-05 - 2029-12-31 {`);
  w('  now 2026-03-02-09:00');
  w('}');
  w();
  for (let r = 0; r < resCount; r++) {
    const id = `r${String(r).padStart(2, '0')}`;
    const eff = (0.8 + ((r * 3) % 5) * 0.1).toFixed(1);
    w(`resource ${id} "Resource ${r + 1}" {`);
    w(`  efficiency ${eff}`);
    w('}');
  }
  w();

  const resId = (k) => `r${String(k).padStart(2, '0')}`;
  const declared = new Set();
  for (const phase of phases) {
    const p = phase.index;
    w(`task p${p} "Phase ${p + 1}" {`);
    for (const pkg of phase.pkgs) {
      const k = pkg.index;
      w(`  task p${p}k${k} "Package ${p + 1}.${k + 1}" {`);
      for (const leaf of pkg.leaves) {
        const id = `t${leaf.seq}`;
        declared.add(leaf.seq);
        w(`    task ${id} "Item ${leaf.seq}" {`);
        if (leaf.dep) w(`      depends ${leaf.dep}`);
        w(`      ${leaf.size}`);
        if (leaf.complete !== undefined) w(`      complete ${leaf.complete}`);
        if (leaf.alloc) w(`      allocate ${leaf.alloc.map(resId).join(', ')}`);
        w('    }');
      }
      w('  }');
    }
    w(`  task ms${p} "Phase ${p + 1} done" {`);
    w('    milestone');
    w(`    depends !p${p}k${phase.pkgs.length - 1}`);
    w('  }');
    w('}');
    w();
  }

  // Count and sanity checks: exact task count, and every absolute dependency names a task.
  const text = out.join('\n') + '\n';
  const taskCount = text.split('\n').filter((l) => /^\s*task\s/.test(l)).length;
  if (taskCount !== n) throw new Error(`gantt-${n}: wrote ${taskCount} tasks, expected ${n}`);
  const milestones = new Set(phases.map((p) => p.index));
  for (const m of text.matchAll(/depends p(\d+)\.p\1k(\d+)\.t(\d+)/g)) {
    if (!declared.has(Number(m[3]))) throw new Error(`gantt-${n}: dangling reference t${m[3]}`);
  }
  // Relative `!tN` names a sibling leaf, and `pX.msX` a phase milestone; both must be declared.
  for (const m of text.matchAll(/!t(\d+)\b/g)) {
    if (!declared.has(Number(m[1]))) throw new Error(`gantt-${n}: dangling relative reference t${m[1]}`);
  }
  for (const m of text.matchAll(/depends p(\d+)\.ms(\d+)\b/g)) {
    if (!milestones.has(Number(m[2]))) throw new Error(`gantt-${n}: dangling milestone reference p${m[1]}.ms${m[2]}`);
  }
  return text;
}

const here = dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes('--check');
let bad = false;
for (const { n, resources, seed } of SIZES) {
  const dest = resolve(here, `../plans/gantt/gantt-${n}/plan.tjp`);
  const text = ganttPlan(n, resources, seed);
  if (check) {
    let current = '';
    try { current = readFileSync(dest, 'utf8'); } catch { /* missing counts as a difference */ }
    if (current !== text) {
      console.error(`${dest} differs from the generated output; run the generator without --check`);
      bad = true;
    } else {
      console.log(`${dest} is up to date`);
    }
  } else {
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, text);
    console.log(`wrote ${dest}: ${n} tasks, ${resources} resources`);
  }
}
if (bad) process.exit(1);
