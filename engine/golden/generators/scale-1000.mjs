// Generates engine/golden/plans/synthetic/20-scale-1000/plan.tjp.
// Deterministic: a seeded mulberry32 PRNG with a fixed seed, no Math.random, no clock.
// Run from anywhere: node engine/golden/generators/scale-1000.mjs
// Check mode: node engine/golden/generators/scale-1000.mjs --check (exit 1 if the committed file differs).
// SPDX-License-Identifier: GPL-2.0-or-later
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// 32-bit seed (0x5ca1e100 = 1554768128); the previous 0x5ca1e1000 did not fit in 32 bits.
const SEED = 0x5ca1e100;
function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rnd = mulberry32(SEED);
const pick = (n) => Math.floor(rnd() * n);

const PHASES = 4;          // level 1: phase
const PACKAGES = 5;        // level 2: work package
const SUBTASKS = 10;       // level 3: subtask
const LEAVES = 5;          // level 4: leaf work item (allocated)
const GROUPS = 6;          // resource groups
const PER_GROUP = 9;       // 54 resources total

const out = [];
const w = (s = '') => out.push(s);

w('# Feature: scale - generated: 1000+ leaf tasks, 54 resources in 6 groups, 4-level nesting, dependency chains, 3-year horizon');
w('# Generated by engine/golden/generators/scale-1000.mjs (seed 0x5ca1e100 = 1554768128, 32-bit). Do not hand-edit; regenerate with the script.');
w('# SPDX-License-Identifier: GPL-2.0-or-later');
w('project scale1000 "Scale 1000" 2026-01-05 - 2028-12-29 {');
w('  now 2026-03-02-09:00');
w('}');
w();

const resIds = [];
for (let g = 0; g < GROUPS; g++) {
  w(`resource grp${g} "Group ${g}" {`);
  for (let r = 0; r < PER_GROUP; r++) {
    const id = `g${g}r${r}`;
    resIds.push([g, id]);
    w(`  resource ${id} "Resource ${g}-${r}" {`);
    w(`    efficiency ${(0.8 + (pick(5) * 0.1)).toFixed(1)}`);
    w('  }');
  }
  w('}');
}
w();

const leafIds = [];
w('task scale "Scale project" {');
for (let p = 0; p < PHASES; p++) {
  w(`  task ph${p} "Phase ${p}" {`);
  for (let k = 0; k < PACKAGES; k++) {
    w(`    task wp${p}_${k} "Package ${p}.${k}" {`);
    for (let s = 0; s < SUBTASKS; s++) {
      w(`      task st${p}_${k}_${s} "Subtask ${p}.${k}.${s}" {`);
      for (let l = 0; l < LEAVES; l++) {
        const id = `t${p}_${k}_${s}_${l}`;
        leafIds.push(id);
        const effort = 2 + pick(4);
        const grp = pick(GROUPS);
        const res = `g${grp}r${pick(PER_GROUP)}`;
        w(`        task ${id} "Item ${p}.${k}.${s}.${l}" {`);
        w(`          effort ${effort}d`);
        if (l > 0) {
          w(`          depends !t${p}_${k}_${s}_${l - 1}`);
        } else if (s === 0 && k >= 0 && p > 0) {
          // chain across phases: lane k of phase p starts after lane k of phase p-1 finished
          w(`          depends scale.ph${p - 1}.wp${p - 1}_${k}.st${p - 1}_${k}_${SUBTASKS - 1}.t${p - 1}_${k}_${SUBTASKS - 1}_${LEAVES - 1}`);
        } else if (s > 0) {
          // chain across subtasks inside the same package
          w(`          depends scale.ph${p}.wp${p}_${k}.st${p}_${k}_${s - 1}.t${p}_${k}_${s - 1}_${LEAVES - 1}`);
        }
        w(`          allocate ${res}`);
        w('        }');
      }
      w('      }');
    }
    w('    }');
  }
  w('  }');
}
w('}');
w();

const here = dirname(fileURLToPath(import.meta.url));
const dest = resolve(here, '../plans/synthetic/20-scale-1000/plan.tjp');
const text = out.join('\n') + '\n';
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(dest, 'utf8'); } catch { /* missing file counts as a difference */ }
  if (current !== text) {
    console.error(`${dest} differs from the generated output; run the generator without --check`);
    process.exit(1);
  }
  console.log(`${dest} is up to date`);
} else {
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, text);
  console.log(`wrote ${dest}: ${leafIds.length} leaf tasks, ${resIds.length} resources`);
}
